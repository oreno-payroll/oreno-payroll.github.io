/** UI layout regression test: settings, unified back buttons, mobile PDF picker. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const source = p => readFileSync(new URL('../' + p, import.meta.url), 'utf8');
const home = source('public/index.html');
const settings = source('public/backup/index.html');
const upload = source('public/upload/index.html');
const shared = source('public/styles/style.css');
const uploadCss = source('public/styles/upload.css');
const uploadTs = source('src/upload.ts');
assert.match(home, /<symbol id="icon-settings"/);
assert.match(home, /class="btn btn--secondary settings-link"[^>]*aria-label="設定"[^>]*title="設定"/);
assert.match(home, /<use href="#icon-settings"><\/use><\/svg><\/a>/);
assert.doesNotMatch(home, /<span>設定<\/span>/);
assert.doesNotMatch(home, /本業と副業の収入を、ひとつの場所で。/);
const dashboardCss = source('public/styles/dashboard.css');
assert.match(dashboardCss, /\.header-actions \.settings-link \.icon \{ display: block;/);
assert.match(dashboardCss, /\.period-switcher__options \{ box-sizing: border-box; height: 44px; padding: 3px; \}/);
assert.match(dashboardCss, /\.period-switcher \.select-field \.select \{ height: 44px; min-height: 44px; \}/);
assert.match(dashboardCss, /\.period-switcher__caption,[\s\S]*?\.period-switcher \.select-field label \{ display: block; margin: 0; line-height: 14px; \}/);
assert.doesNotMatch(home, /<use href="#icon-backup"/);
const back = /<a class="btn btn--secondary header-back" href="\.\.\/index\.html">\s*<svg class="icon" aria-hidden="true"><use href="#icon-arrow"><\/use><\/svg>\s*<span>ホームへ戻る<\/span>\s*<\/a>/;
assert.match(settings, back);
assert.match(upload, back);
assert.match(shared, /\.site-header \.header-back\{/);
assert.doesNotMatch(uploadCss, /\.header-back span \{ display: none; \}/);
assert.match(upload, /id="mobile-file-picker"[^>]*type="button"/);
assert.match(upload, /id="file-input"[^>]*multiple hidden/);
assert.match(uploadCss, /@media\(max-width:640px\)[\s\S]*?\.upload-zone-card #drop-zone\{display:none\}/);
assert.match(uploadCss, /\.mobile-file-picker-wrap\{display:flex/);
assert.match(uploadTs, /mobileFilePicker\.addEventListener\("click", \(\) => \{ if \(!fileInput\.disabled\) fileInput\.click\(\); \}\)/);
// Both cloud writes and read-only recovery checks must block new PDF selection.
assert.match(uploadTs, /mobileFilePicker\.disabled = saving \|\| uploadSaveRecoveryChecking;/);
assert.match(uploadTs, /fileInput\.disabled = saving \|\| uploadSaveRecoveryChecking;/);
assert.match(uploadTs, /clearButton\.disabled = saving \|\| uploadSaveRecoveryChecking;/);
assert.match(uploadTs, /saveButton\.disabled = saving \|\| uploadSaveRecoveryRequired \|\| uploadSaveRecoveryChecking \|\|/);
assert.match(uploadTs, /uploadRecoveryReload\.disabled = saving \|\| uploadSaveRecoveryChecking \|\| !uploadSaveRecoveryRequired \|\| !uploadSaveRecoveryChecked;/);
console.log('PASS: icon-only settings, matched period controls, back navigation, mobile picker, desktop drop zone');
