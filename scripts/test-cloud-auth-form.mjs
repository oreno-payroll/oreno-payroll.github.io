/** The sign-in and unlock gate shows only the controls needed for each step. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const auth=source('src/cloud/auth.ts');
const css=source('public/styles/cloud.css');
const theme=source('public/styles/theme.css');
const markup=auth.match(/panel\.innerHTML=`([\s\S]*?)`;/)?.[1];
assert.ok(markup,'auth gate markup exists');
const login=markup.match(/<form id="payroll-cloud-login-form"[\s\S]*?<\/form>/)?.[0];
const unlock=markup.match(/<form id="payroll-cloud-unlock-form"[\s\S]*?<\/form>/)?.[0];
assert.ok(login && unlock,'separate sign-in and password forms');
assert.match(login,/autocomplete="off"/);
assert.match(login,/<label for="payroll-client-id">Client ID<\/label>/);
assert.match(login,/id="payroll-client-id"[^>]*form="payroll-cloud-login-form"/);
assert.match(login,/id="payroll-login" type="submit"[^>]*>Microsoftアカウントに接続<\/button>/);
assert.doesNotMatch(login,/Microsoft接続設定を変更|初回のみ|パスフレーズ/);
assert.match(unlock,/autocomplete="on"/);
assert.match(unlock,/id="payroll-passphrase" type="password" name="password" autocomplete="current-password"/);
assert.match(unlock,/id="payroll-unlock" type="submit"[^>]*>保管庫を開く<\/button>/);
assert.match(unlock,/payroll-cloud-remember/,'opt-in temporary key retention remains');
assert.match(unlock,/id="payroll-unlock-error"[^>]*hidden/,'error is hidden above unlock button');
assert.doesNotMatch(markup,/OneDriveの明細を復号します|初回のみClient ID|Microsoft接続設定を変更|パスフレーズはこの端末へ保存しません|Microsoftログイン成功|payroll-cloud-status|payroll-cloud-account|<details/);
assert.match(auth,/ui\.loginForm\.addEventListener\('submit',event=>\{event\.preventDefault\(\)/);
assert.match(auth,/ui\.unlockForm\.addEventListener\('submit',event=>\{event\.preventDefault\(\)/);
assert.match(auth,/ui\.id\.addEventListener\('change',onClientIdEdited\)/);
assert.match(auth,/ui\.id\.addEventListener\('input',onClientIdEdited\)/);
assert.match(auth,/showGateError\(ui\.loginError/);
assert.match(auth,/showGateError\(ui\.unlockError/);
assert.match(auth,/ui\.loginForm\.hidden=state==='connected'\|\|state==='checking'/);
assert.match(auth,/ui\.unlockForm\.hidden=state!=='connected'/);
assert.match(css,/\.payroll-cloud-error\[hidden\]\{display:none\}/);
assert.match(theme,/html\[data-theme="dark"\] \.payroll-cloud-error/);
console.log('PASS: minimal login and unlock gate, visible errors only on failure, autofill retained');
