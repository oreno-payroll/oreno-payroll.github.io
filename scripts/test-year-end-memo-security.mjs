import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const mod=await import('data:text/javascript;base64,'+Buffer.from(stripTypeScriptTypes(read('src/yearEnd/model.ts'),{mode:'strip'})).toString('base64'));
const id=mod.randomPersonId(),base=mod.emptyYear(id,2026);
