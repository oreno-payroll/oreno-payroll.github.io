/** Preservation checks run without real salary data or Microsoft credentials. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createPayrollSemantics,isValidPayrollSemantics} from '../src/storage/payrollSemantics.ts';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const example={job:'main',kind:'salary',targetMonth:'2026-11',paymentDate:'2026-11-27',taxable:'150000'};
const old=createPayrollSemantics(example,{profile:'main',fields:{},warnings:[],missingFields:[],fieldSources:{taxable:{page:1,label:'当時の課税支給合計',labelX:0,labelY:0,valueX:1,valueY:1}}});
assert.ok(isValidPayrollSemantics(old));
assert.equal(old.fieldLabels.taxable,'当時の課税支給合計');
assert.equal(old.roleAtImport,'main');
assert.equal(old.kindAtImport,'salary');
assert.equal(isValidPayrollSemantics({...old,fieldLabels:{}}),false);
assert.equal(isValidPayrollSemantics({...old,parserRevision:'../../invalid'}),false);
const store=read('src/storage/payrollStore.ts');
assert.match(store,/semantics\?:PayrollStatementSemantics/);
assert.match(store,/record\.semantics\?\?null/);
const vault=read('src/cloud/vault.ts');
assert.match(vault,/isValidPayrollSemantics\(rec\.semantics\)/);
const upload=read('src/upload.ts');
assert.match(upload,/semantics: createPayrollSemantics\(entry\.form,entry\.parsed\)/);
const ui=read('src/year-end-assist.ts');
assert.doesNotMatch(ui,/method==='manual'\)input\.value=methodChanged\?'':/);
assert.match(ui,/if\(input\.dataset\.userEdited==='true'\)continue/);
assert.match(ui,/if\(method==='manual'\)input\.value=oldZero\?'0':existing\?String\(existing\.amount\):methodChanged\?'':input\.value/);
const repository=read('src/yearEnd/repository.ts');
assert.match(repository,/method==='manual'&&old&&old\.amount===nextEstimate\.amount\?old:nextEstimate/);
const auth=read('src/cloud/auth.ts');
assert.match(auth,/id="payroll-cloud-config"/);
assert.match(auth,/id="payroll-cloud-edit-id"/);
assert.match(auth,/ui\.settings\.hidden=hasClientId/);
console.log('PASS: historical labels and parser provenance, non-destructive estimate edits, tidy Microsoft sign-in');
