import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const load=async path=>import('data:text/javascript;base64,'+Buffer.from(stripTypeScriptTypes(read(path),{mode:'strip'})).toString('base64'));
const m=await load('src/yearEnd/model.ts');
const cryptoMod=await load('src/cloud/crypto.ts');
const id=m.randomPersonId(),other=m.randomPersonId();
assert.notEqual(id,other,'same names get distinct UUID identity');
const mk=(month,kind,taxable)=>({id:m.randomDocumentId(),personId:id,kind,paymentDate:`2026-${month}-25`,targetMonth:`2026-${month}`,taxable,
 gross:taxable+50000,transportation:10000,nonTaxable:10000,healthInsurance:1000,pension:1000,employmentInsurance:100,incomeTax:2000,residentTax:1000,
 fileName:'synthetic.pdf',pdfSize:900,fileHash:crypto.randomUUID().replaceAll('-','').padEnd(64,'a').slice(0,64),confirmedAt:'2026-11-01T00:00:00Z',updatedAt:'2026-11-01T00:00:00Z',source:'pdf-reviewed',revision:1});
const a=mk('08','salary',245000),b=mk('09','salary',260000),c=mk('10','salary',255000);
const bonus1=mk('08','bonus',100000),bonus2=mk('08','bonus',130000);
const year={...m.emptyYear(id,2026),documents:[a,b,c,bonus1,bonus2]};
assert.equal(m.validateYear(year,id,2026),year);
const actual=m.calculateYear(year);assert.equal(actual.salary,760000);assert.equal(actual.bonus,230000);assert.equal(actual.actual,990000);
const snapshot=JSON.stringify(year);
const three=m.forecastPreview(year,'average3',['2026-11','2026-12']);
assert.deepEqual(three.references.map(r=>r.amount),[255000,260000,245000]);
assert.deepEqual(three.estimated.map(e=>e.amount),[253333,253333]);
assert.equal(three.forecastTotal,506666);assert.equal(three.annualTotal,1496666);
assert.equal(JSON.stringify(year),snapshot,'preview does not persist or mutate');
const bonusEstimate=m.bonusEstimatePreview(year,'2026-12',50000);
assert.equal(bonusEstimate.annualTotal,1040000);
assert.throws(()=>m.bonusEstimatePreview(year,'2026-08',50000),/賞与実績/);
const withBonus={...year,bonusEstimates:[{month:'2026-12',amount:50000,method:'manual',references:[],updatedAt:'2026-11-01'}]};
assert.equal(m.calculateYear(withBonus).forecast,50000);
assert.equal(m.forecastPreview(withBonus,'latest',['2026-11']).annualTotal,1295000);
const latest=m.forecastPreview(year,'latest',['2026-11','2026-12']);
assert.deepEqual(latest.estimated.map(e=>e.amount),[255000,255000]);
const manual=m.forecastPreview(year,'manual',['2026-11','2026-12'],{'2026-11':250001,'2026-12':250002});
assert.equal(manual.annualTotal,1490003);
assert.equal(m.forecastPreview({...year,documents:[a]},'average3',['2026-11']).references.length,1);
assert.throws(()=>m.validateYear({...year,documents:[...year.documents,mk('10','salary',400)]},id,2026),/重複/);
assert.throws(()=>m.validateYear({...year,estimates:[{month:'2026-10',amount:255000,method:'manual',references:[],updatedAt:'2026-11-01'}]},id,2026),/重複/);
assert.throws(()=>m.validateYear({...year,personId:other},id,2026),/不正/);
assert.throws(()=>m.forecastPreview(year,'latest',['2026-10']),/確定済み/);
assert.equal(m.parseYen('260,000円'),260000);assert.equal(m.parseYen('250.5'),null);
